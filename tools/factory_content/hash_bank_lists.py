#!/usr/bin/env python3
"""Adds each file's SHA-256 to the bank lists (content/factory/BankLists), from the banks on this computer.

    python tools/factory_content/hash_bank_lists.py [--banks FOLDER] [--lists FOLDER]

A list's entry becomes [path, size, lfs, recipe or null, sha256]; CyDAW checks a downloaded file
against it (SoundBanks) and refuses one of the right size but other bytes. Only a file found on disk
at the listed size is hashed: the others keep no hash (and are checked by their size alone, as
before). Nothing is downloaded, and nothing else in the lists changes. The banks CyDAW makes itself
(their entries carry a recipe) are left as they are. build_bank_registry.py writes the hashes too.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fetch_banks import default_destination  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for piece in iter(lambda: handle.read(1 << 20), b""):
            digest.update(piece)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--banks", type=Path, default=default_destination())
    parser.add_argument("--lists", type=Path, default=ROOT / "content" / "factory" / "BankLists")
    args = parser.parse_args()
    total_hashed = total_missing = 0
    for list_path in sorted(args.lists.glob("*.json")):
        bank = list_path.stem
        document = json.loads(list_path.read_text(encoding="utf-8"))
        entries = document.get("files", [])
        if any(len(entry) > 3 and isinstance(entry[3], dict) for entry in entries):
            print(json.dumps({"bank": bank, "skipped": "generated by CyDAW"}), flush=True)
            continue
        hashed = missing = 0
        for index, entry in enumerate(entries):
            path, size = entry[0], int(entry[1])
            local = args.banks / bank / path
            if not local.is_file() or local.stat().st_size != size:
                missing += 1
                continue
            lfs = int(entry[2]) if len(entry) > 2 and entry[2] else 0
            recipe = entry[3] if len(entry) > 3 else None
            entries[index] = [path, size, lfs, recipe, sha256_of(local)]
            hashed += 1
        # One file a line, as build_bank_registry.py writes them.
        body = ",\n".join(json.dumps(entry, ensure_ascii=False) for entry in entries)
        list_path.write_text('{"files": [\n' + body + "\n]}\n", encoding="utf-8")
        total_hashed += hashed
        total_missing += missing
        print(json.dumps({"bank": bank, "hashed": hashed, "notOnDisk": missing}), flush=True)
    print(json.dumps({"hashed": total_hashed, "notOnDisk": total_missing}), flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
