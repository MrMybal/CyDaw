"""Quartz's factory sounds (the four-operator FM synth of the family): each a few
settings over the defaults ("Init" first), keys as in Quartz's table, a choice
by its English name. The defaults: operator 1 the carrier (level 0.8), operator
2 modulating it ("m.21" 0.35), operators 3 and 4 silent, whole ratios on, a
gentle low-pass at 9 kHz, the volume's envelope held at its top (the
operators' own envelopes shape the sound) with a release of 0.35 s.

A modulation "m.<from><to>" goes from one operator to another (its own:
feedback); "m.n<to>" is the noise into one. The volume's release cuts the
operators' releases: a long ringing sound sets both.
"""
from __future__ import annotations


def op(number: int, **settings) -> dict:
    """One operator's settings: op(2, ratio=3.5, decay=0.4) -> {"op2.ratio": 3.5, "op2.decay": 0.4}."""
    return {f"op{number}.{key}": value for key, value in settings.items()}


